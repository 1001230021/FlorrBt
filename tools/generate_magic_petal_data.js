#!/usr/bin/env node
"use strict";
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
const sourcePath = path.join(root, "src", "Shared", "magic_petal_data.h");
const outputPath = path.join(root, "web", "src", "generated_magic_petal_data.js");
const source = fs.readFileSync(sourcePath, "utf8");
const names = [
  "orb_mana_restore_common", "base_mana_capacity_common", "magic_leaf_mana_regen_common",
  "magic_lightning_damage_common", "magic_lightning_mana_cost_common",
  "magic_lightning_reload_seconds", "magic_cactus_mana_capacity_common",
];
const values = {};
for (const name of names) {
  const match = new RegExp(`inline\\s+constexpr\\s+float\\s+${name}\\s*=\\s*([0-9]+(?:\\.[0-9]*)?)f`).exec(source);
  if (!match) throw new Error(`missing literal ${name}`);
  values[name] = Number(match[1]);
}
fs.writeFileSync(outputPath,
  "// AUTO-GENERATED by tools/generate_magic_petal_data.js - DO NOT EDIT.\n" +
  `export const MAGIC_PETAL_DATA = Object.freeze(${JSON.stringify(values, null, 2)});\n`, "utf8");
console.log(`[generate_magic_petal_data] wrote ${path.relative(root, outputPath)}`);
