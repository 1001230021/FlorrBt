import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => readFileSync(path.join(root, file), 'utf8');
const context = read('src/Server/Game/gamecontext.h');
const network = read('src/Server/Module/network_module.h');
const transition = read('src/Server/Game/world_transition.cpp');
const entity = read('src/Server/Game/entity.h');
const controller = read('src/Server/Game/gamecontroller.h');
assert.doesNotMatch(context, /CGameWorld& m_world|CGameWorld& World\(/);
assert.doesNotMatch(network, /m_lobby_world|CGameWorld& lobby/);
assert.match(context, /m_worlds\.GetMainWorld\(\)/);
assert.doesNotMatch(entity, /CanTransferBetweenWorlds/);
assert.match(entity, /CollectTransferDependencies/);
assert.match(entity, /RemapTransferredReferences/);
assert.doesNotMatch(controller, /OnPlayerEnteredWorld|OnPlayerLeftWorld/);
assert.match(controller, /ValidatePlayerTransition\(const SPlayerTransitionView&/);
assert.match(transition, /before_source\.Restore\(\); before_destination\.Restore\(\)/);
assert.ok(transition.indexOf('player.CommitOwnedEntity(controlled)') < transition.indexOf('OnPlayerDepartureCommitted(source'));
assert.match(read('src/Server/Game/world_transition.h'), /bool committed = false/);
console.log('PASS main-world resolver, structural transfer/remap, rollback and committed-notification architecture');
